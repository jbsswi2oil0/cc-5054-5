#!/usr/bin/env node
// Render the documentation examples into a single readable document.
//
//   node tools/doc/docs.mjs            print to stdout
//   node tools/doc/docs.mjs --write    write docs/format-examples.md
//
// Everything shown here is read back from examples/*.json, which
// tools/doc/examples.mjs generated from coefficient tables.  Sections that
// would otherwise be prose (the coefficient tables, the bit positions) are
// emitted from that data, so the document cannot drift from the streams.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const write = process.argv.includes("--write");

const read = (p) => JSON.parse(readFileSync(join(ROOT, "examples", p), "utf8"));
const se = read("shared-edge/manifest.json");
const mn = read("minimal/manifest.json");
const legacyExists = (() => { try { read("legacy/blocks-v1.json"); return true; } catch { return false; } })();
const lg = legacyExists ? read("legacy/blocks-v1.json") : null;

const lines = [];
const emit = (...xs) => lines.push(...xs);

emit("# IVC1 documented examples", "");
emit("Generated by `node tools/doc/docs.mjs --write` from `examples/*.json`.", "");
emit("Every stream here was written by `tools/doc/miniwriter.mjs` from a plain");
emit("coefficient table; the main encoder (`src/encode.js`) is not called.", "");

emit("## Smallest example", "");
emit(mn.description, "");
emit("| field | bits | value |", "|---|---|---|");
emit(`| header | 0..${mn.headerBits} | magic, version, ${mn.headerBits === 79 ? "size" : ""}, qbase, flags |`);
const f = mn.fields;
emit(`| qsel | ${f.qsel.start}..${f.qsel.end} | 0 |`);
emit(`| mode | ${f.mode.start}..${f.mode.end} | 0 (RAW) |`);
emit(`| numAC | ${f.numAC.start}..${f.numAC.end} | 1 |`);
emit(`| DC | ${f.dc.start}..${f.dc.end} | ${mn.levels[0]} |`);
emit("", `Total ${mn.totalBits} bits, ${mn.byteLength} bytes.  Block bits:`, "");
emit("```", mn.bits, "```", "");
emit("Hex:", "", "```", mn.hex, "```", "");

emit("## Two blocks sharing a prediction edge", "");
emit(se.description, "");
emit("Coefficient tables (zig-zag levels, DC first):", "");
emit("```");
for (const c of se.coefficients) emit(`block ${c.block}: qsel=${c.qsel} mode=${c.mode} dc=${c.dc} ac=[${c.ac.join(", ")}]`);
emit("```", "");
emit(`Block 0 occupies bits [${se.layout.blocks[0].startBit}, ${se.layout.blocks[0].endBit}) ` +
     `and ends on a byte boundary.  Its last AC level is ${se.block0LastCoefficient.level} ` +
     `at zig-zag position ${se.block0LastCoefficient.z}, carried by bits ` +
     `[${se.block0LastCoefficient.bitRange.start}, ${se.block0LastCoefficient.bitRange.end}).`);
emit(`Block 1 uses mode ${se.layout.blocks[1].mode} (H) and predicts from block 0's right column.`, "");
emit("Published block directory (only verified entries):", "");
emit("| block | bits | published |", "|---|---|---|");
for (const b of se.layout.blocks) emit(`| ${b.block} | ${b.startBit}..${b.endBit} | ${b.published} |`);
emit("", "### Damaged tails", "");
emit("| damage | bytes | reported at bit | block | note |", "|---|---|---|---|---|");
const dmg = se.damage;
emit(`| missing last byte | ${dmg.missingLastByte.byteCount} | ${dmg.missingLastByte.failureBit} | ${dmg.missingLastByte.failureIndex} | true last byte lost |`);
emit(`| misplaced end marker | ${dmg.misalignedMarker.byteCount} | ${dmg.misalignedMarker.failureBit} | ${dmg.misalignedMarker.failureIndex} | byte count correct |`);
emit("", "The two report at different bit positions: the real byte loss fails inside");
emit(`block ${dmg.missingLastByte.failureIndex} at bit ${dmg.missingLastByte.failureBit}, while the byte-complete but`);
emit(`mis-aligned stream fails at the stored end, bit ${dmg.misalignedMarker.failureBit}.`, "");
emit("### A bit flip that only the neighbour reveals", "");
const fl = dmg.sharedEdgeFlip;
emit(`Bit ${fl.flippedBit} (inside block 0's last AC codeword) is inverted.  ` +
  `Block 1's own codewords and bit range are unchanged: ${fl.block1TokenUnchanged}.`);
emit(`The decode still reports success: ${fl.decodeStillOk}.`);
if (fl.wrongPixel) {
  emit(`Pixel (${fl.wrongPixel.x}, ${fl.wrongPixel.y}) in block 1 is ${fl.wrongPixel.intact} in the intact`);
  emit(`stream and ${fl.wrongPixel.flipped} in the damaged one, although block 1's payload is identical.`);
}
emit("", "## Checking and reverse lookup", "");
emit("```");
emit("node tools/doc/check.mjs check   examples/shared-edge/stream.ivc");
emit("node tools/doc/check.mjs check   examples/shared-edge/unknown-version.ivc");
emit("node tools/doc/check.mjs check   examples/shared-edge/missing-last-byte.ivc");
emit("node tools/doc/check.mjs lookup  examples/shared-edge/stream.ivc 8 0");
emit("node tools/doc/check.mjs explain examples/shared-edge/shared-edge-flip.ivc examples/shared-edge/stream.ivc 8 0");
emit("node tools/doc/check.mjs directory examples/shared-edge/missing-last-byte.ivc");
emit("node tools/doc/check.mjs seek    examples/shared-edge/stream.ivc 1");
emit("```", "");
emit("The unknown-version stream is rejected at bits " +
  `[${se.unknownVersion.bitRange.start}, ${se.unknownVersion.bitRange.end}) = "${se.unknownVersion.bits}", ` +
  "with no block-level failure reported.", "");

if (lg) {
  emit("## Published legacy example", "");
  emit(`\`examples/legacy/blocks-v1.ivc\` is frozen at ${lg.byteLength} bytes / ${lg.totalBits} bits.`);
  emit("`node tools/doc/side-by-side.mjs` prints its raw bits next to a freshly parsed");
  emit("stream, so the parser and the miniature writer are checked against the published");
  emit("example rather than against each other.", "");
}

emit("## Rebuilding after a quantiser change", "");
emit("```");
emit("node tools/doc/quantiser.mjs --table new-qm.json --diff old-qm.json");
emit("```", "");
emit("Reports, per documented sample, whether the rebuilt stream changes length and");
emit("whether the OLD decoder still returns the original pixels from it.", "");

const text = lines.join("\n");
if (write) {
  const out = join(ROOT, "docs", "format-examples.md");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.error(`wrote ${out}`);
} else {
  console.log(text);
}
